CREATE TABLE IF NOT EXISTS `category` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `type` INT DEFAULT NULL COMMENT '类型: 1 菜品分类 2 套餐分类',
  `name` VARCHAR(32) NOT NULL COMMENT '分类名称',
  `sort` INT DEFAULT NULL COMMENT '顺序',
  `status` INT DEFAULT NULL COMMENT '分类状态 0 标识禁用 1 表示启用',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `create_user` BIGINT DEFAULT NULL COMMENT '创建人',
  `update_user` BIGINT DEFAULT NULL COMMENT '修改人',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='分类表';

CREATE TABLE IF NOT EXISTS `dish` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `name` VARCHAR(32) NOT NULL COMMENT '菜品名称',
  `category_id` BIGINT DEFAULT NULL COMMENT '菜品分类id',
  `price` DECIMAL(10,2) DEFAULT NULL COMMENT '菜品价格',
  `image` VARCHAR(255) DEFAULT NULL COMMENT '图片',
  `description` VARCHAR(500) DEFAULT NULL COMMENT '描述信息',
  `status` INT DEFAULT NULL COMMENT '0 停售 1 起售',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  `create_user` BIGINT DEFAULT NULL COMMENT '创建人',
  `update_user` BIGINT DEFAULT NULL COMMENT '修改人',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='菜品表';

CREATE TABLE IF NOT EXISTS `dish_flavor` (
  `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  `dish_id` BIGINT DEFAULT NULL COMMENT '菜品id',
  `name` VARCHAR(32) DEFAULT NULL COMMENT '口味名称',
  `value` VARCHAR(255) DEFAULT NULL COMMENT '口味数据list',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='菜品口味表';

CREATE TABLE IF NOT EXISTS `setmeal` (
